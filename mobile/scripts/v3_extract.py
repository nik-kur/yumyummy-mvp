"""Extract chart SVGs and feature rows from V3 canvas artboards into TS data.

    python3 scripts/v3_extract.py <canvas project dir>

Writes src/onb/generated/features.ts. The charts are kept as element lists
(path / circle / rect / text with their attributes) and drawn by SvgSpec.
"""
import json
import os
import re
import sys
import html

BLOB_TO_ASSET = {
    'd3281d47': 'feat_snap', '560cf2ba': 'feat_verified', 'c08f082e': 'feat_target',
    '3a8ae84f': 'bar_takeaway', '06713a43': 'acc_flame',
}

ATTR = re.compile(r'([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"')


def camel(k):
    parts = k.split('-')
    return parts[0] + ''.join(p.title() for p in parts[1:])


def svg_spec(svg):
    m = re.match(r'<svg width="(\d+)" height="(\d+)"(?: viewBox="0 0 (\d+) (\d+)")?', svg)
    w, h = int(m.group(1)), int(m.group(2))
    if m.group(3):
        w, h = int(m.group(3)), int(m.group(4))
    grads = []
    for gid, gattrs, stops in re.findall(r'<linearGradient id="([^"]+)"([^>]*)>(.*?)</linearGradient>', svg, re.S):
        g = {camel(k): v for k, v in ATTR.findall(gattrs)}
        g['id'] = gid
        g['stops'] = [{camel(k): v for k, v in ATTR.findall(a)} for a in re.findall(r'<stop ([^>]*)>', stops)]
        grads.append(g)
    svg = re.sub(r'<defs>.*?</defs>', '', svg, flags=re.S)
    els = []
    for tag, attrs, inner in re.findall(r'<(path|circle|rect|text|line)\s([^>]*?)(?:/>|>(.*?)</\1>)', svg, re.S):
        a = {camel(k): v for k, v in ATTR.findall(attrs)}
        if tag == 'text':
            a['children'] = html.unescape(inner)
        a['t'] = tag
        els.append(a)
    return {'w': w, 'h': h, 'els': els, 'grads': grads}


def text(s):
    return html.unescape(re.sub(r'<[^>]+>', '', s)).strip()


def body_of(path):
    s = open(path).read()
    b = s.split('<x-dc>')[1].split('</x-dc>')[0]
    return re.sub(r'<helmet>.*?</helmet>', '', b, flags=re.S)


def also_rows(b):
    j = b.index('Also in YumYummy')
    rows = []
    for blob, title, sub in re.findall(
        r'<img src="/_blob/([0-9a-f]{8})[0-9a-f]*"[^>]*>\s*<div[^>]*><span[^>]*>([^<]*)</span><span[^>]*>([^<]*)</span>',
        b[j:],
    ):
        rows.append({'icon': BLOB_TO_ASSET[blob], 'title': html.unescape(title), 'sub': html.unescape(sub)})
    return rows


def main(project):
    out = {}
    for name in ['Features_yes', 'Features_yes_accuracy', 'Features_yes_gave_up', 'Features_yes_eating_out',
                 'Features_yes_other', 'Features_no', 'Features_no_same', 'Features_no_up']:
        b = body_of(os.path.join(project, f'V3_{name}.dc.html'))
        title = text(re.search(r'<h1[^>]*>(.*?)</h1>', b, re.S).group(1))
        entry = {'title': title, 'also': also_rows(b)}
        if name.startswith('Features_yes'):
            hero = b[b.index('YumYummy is different'):b.index('Also in YumYummy')]
            items = re.findall(
                r'<img src="/_blob/([0-9a-f]{8})[0-9a-f]*"[^>]*>\s*<div[^>]*><span[^>]*>([^<]*)</span><span[^>]*>([^<]*)</span>',
                hero,
            )
            entry['hero'] = [{'icon': BLOB_TO_ASSET[i], 'title': html.unescape(t), 'sub': html.unescape(s)} for i, t, s in items]
        else:
            card = b[b.index('<h1'):b.index('Also in YumYummy')]
            entry['chartLabel'] = text(re.search(r'<span style="font-size: 15px; line-height: 20px; font-weight: 600">(.*?)</span>', card).group(1))
            entry['chart'] = svg_spec(re.search(r'<svg width="300".*?</svg>', card, re.S).group(0))
            spans = re.findall(r'<span style="margin-top: 12px; text-align: center;[^"]*">(.*?)</span>', card, re.S)
            entry['claim'] = text(spans[0]) if spans else ''
            src = re.search(r'<a href="#"[^>]*><span>(.*?)</span>', card)
            entry['source'] = text(src.group(1)) if src else None
        out[name] = entry
    plans = {}
    for name in ['PlanReveal', 'PlanReveal_gain', 'PlanReveal_maintain', 'PlanReveal_recomp']:
        b = body_of(os.path.join(project, f'V3_{name}.dc.html'))
        plans[name] = svg_spec(re.search(r'<svg width="308".*?</svg>', b, re.S).group(0))
    dst = os.path.join(os.path.dirname(__file__), '..', 'src', 'onb', 'generated')
    os.makedirs(dst, exist_ok=True)
    with open(os.path.join(dst, 'planCharts.ts'), 'w') as f:
        f.write('/* Generated by scripts/v3_extract.py from the V3 canvas. Do not edit by hand. */\n')
        f.write("import type { SvgSpecData } from '@/components/onb/SvgSpec';\n\n")
        f.write('export const PLAN_CHARTS: Record<string, SvgSpecData> = ')
        f.write(json.dumps(plans, indent=2, ensure_ascii=False))
        f.write(';\n')
    os.makedirs(dst, exist_ok=True)
    with open(os.path.join(dst, 'features.ts'), 'w') as f:
        f.write('/* Generated by scripts/v3_extract.py from the V3 canvas. Do not edit by hand. */\n')
        f.write('import type { FeaturesArtboard } from \'../featuresTypes\';\n\n')
        f.write('export const FEATURES: Record<string, FeaturesArtboard> = ')
        f.write(json.dumps(out, indent=2, ensure_ascii=False))
        f.write(';\n')
    print('ok', list(out))


if __name__ == '__main__':
    main(sys.argv[1])
